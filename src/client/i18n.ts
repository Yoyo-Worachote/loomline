export type Key = keyof typeof DICT;
type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const raw: string = DICT[key][lang === 'th' ? 0 : 1];
  return vars ? raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : raw;
}

export interface Translator {
  (key: Key, vars?: Vars): string;
  lang: Lang;
  /** Pick the right language from bilingual data. */
  l(text: LText): string;
}

export function makeTranslator(lang: Lang): Translator {
  return Object.assign((key: Key, vars?: Vars) => translate(lang, key, vars), { lang, l: (x: LText) => x[lang] });
}

// Stable identities, so translators can sit in effect dependency lists.
const TRANSLATORS = { th: makeTranslator('th'), en: makeTranslator('en') };

export function useT(): Translator {
  return TRANSLATORS[usePrefs().lang];
}

